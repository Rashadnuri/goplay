// Generates src/content/bank.generated.ts. Accepted answers come from the rules engine / exhaustive search.
//   npx tsx scripts/gen-bank.ts
import { writeFileSync } from 'node:fs';
import { BLACK, WHITE, GoGame, makeConfig, type Color } from '../src/engine/index.ts';
import { enclosure, solutions, type Verify } from '../src/engine/puzzles.ts';

const pad = (rows: string[]) => [...rows, ...Array(9 - rows.length).fill('.........')].map((r) => r.padEnd(9, '.'));
const P = (x: number, y: number) => y * 9 + x;
interface Spec { id: string; difficulty: 1 | 2 | 3; kind: string; rows: string[]; toPlay: Color; verify: Verify; shape?: string }
const specs: Spec[] = [];

// ── difficulty 1: capture / atari ──
specs.push({ id: 'cap-1', difficulty: 1, kind: 'capture', rows: pad(['....X....', '...XOX...']), toPlay: BLACK, verify: { kind: 'capture' } });
specs.push({ id: 'cap-2', difficulty: 1, kind: 'capture', rows: pad(['OX', '.']), toPlay: BLACK, verify: { kind: 'capture' } });
specs.push({ id: 'cap-3', difficulty: 1, kind: 'capture', rows: pad(['..XOO....', '...XX....']), toPlay: BLACK, verify: { kind: 'capture', min: 2 } });
specs.push({ id: 'cap-4', difficulty: 1, kind: 'capture', rows: pad(['XO.', 'XX']), toPlay: BLACK, verify: { kind: 'capture' } });
specs.push({ id: 'atari-1', difficulty: 1, kind: 'atari', rows: pad(['', '', '', '....X', '...XO']), toPlay: BLACK, verify: { kind: 'atari' } });
// ── difficulty 2: double atari / escape / connect / bigger capture ──
specs.push({ id: 'dbl-1', difficulty: 2, kind: 'doubleAtari', rows: pad(['', '', '..X.X', '.XO.OX']), toPlay: BLACK, verify: { kind: 'doubleAtari' } });
specs.push({ id: 'esc-1', difficulty: 2, kind: 'escape', rows: pad(['', '', '', '....O', '...OXO']), toPlay: BLACK, verify: { kind: 'escape', target: P(4, 4) } });
specs.push({ id: 'con-1', difficulty: 2, kind: 'connect', rows: pad(['', '', '', '....O', '...X.X', '....O']), toPlay: BLACK, verify: { kind: 'connect', a: P(3, 4), b: P(5, 4) } });
specs.push({ id: 'cap-5', difficulty: 2, kind: 'capture', rows: pad(['.XXX.', 'XOOOX', 'X.XOX', '.XXX']), toPlay: BLACK, verify: { kind: 'capture', min: 3 } });
specs.push({ id: 'atari-2', difficulty: 2, kind: 'atari', rows: pad(['', '', '', '..XOX', '..XOX']), toPlay: BLACK, verify: { kind: 'atari' } });
// ── difficulty 3: life & death, proven by exhaustive search ──
const shapes: [string, [number, number][]][] = [
  ['line3', [[1, 0], [2, 0], [3, 0]]], ['bent3', [[0, 0], [1, 0], [0, 1]]], ['tfour', [[1, 0], [2, 0], [3, 0], [2, 1]]],
  ['cross5', [[1, 0], [0, 1], [1, 1], [2, 1], [1, 2]]], ['pyramid5', [[1, 0], [2, 0], [3, 0], [2, 1], [1, 1]]],
];
for (const [shape, eye] of shapes) {
  const { rows, region, target } = enclosure(9, eye);
  specs.push({ id: `ld-${shape}-live`, difficulty: 3, kind: 'lifeDeath', shape, rows, toPlay: BLACK, verify: { kind: 'lifeDeath', target, region, role: 'live' } });
  if (shape !== 'pyramid5' || true) specs.push({ id: `ld-${shape}-kill`, difficulty: 3, kind: 'lifeDeath', shape, rows, toPlay: WHITE, verify: { kind: 'lifeDeath', target, region, role: 'kill' } });
}

let out = '// GENERATED by scripts/gen-bank.ts — answers are computed by the rules engine / exhaustive search. Do not edit.\nimport type { BankPuzzle } from \'./bank.ts\';\nexport const GENERATED: BankPuzzle[] = [\n';
for (const s of specs) {
  const g = GoGame.fromPosition(makeConfig({ size: 9 }), s.rows, s.toPlay);
  const pts = solutions(g, s.verify);
  if (pts.length === 0) throw new Error(`${s.id}: no solution`);
  console.log(s.id.padEnd(22), JSON.stringify(pts.map((p) => [p % 9, Math.floor(p / 9)])));
  out += `  ${JSON.stringify({ id: s.id, difficulty: s.difficulty, kind: s.kind, shape: s.shape, size: 9, rows: s.rows, toPlay: s.toPlay, points: pts, verify: s.verify })},\n`;
}
out += '];\n';
writeFileSync(new URL('../src/content/bank.generated.ts', import.meta.url), out);
