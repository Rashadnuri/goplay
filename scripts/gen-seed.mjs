// Generates supabase/seed.sql: lessons (basics + opening library) and the puzzle bank.
// Answers go to puzzle_solutions, which clients cannot read; the public `puzzles` rows never contain them.
//   npx tsx scripts/gen-seed.mjs
import { writeFileSync } from 'node:fs';
import { LESSONS } from '../src/content/lessons.ts';
import { BANK } from '../src/content/bank.ts';

const q = (o) => `'${JSON.stringify(o).replace(/'/g, "''")}'::jsonb`;
let sql = '-- generated by scripts/gen-seed.mjs\n';
for (const l of LESSONS) {
  sql += `insert into public.lessons (slug, position, level, track, title, summary, steps) values ('${l.slug}', ${l.position}, ${l.level}, '${l.track ?? 'basics'}', ${q(l.title)}, ${q(l.summary)}, ${q(l.steps)}) on conflict (slug) do nothing;\n`;
}
for (const p of BANK) {
  const shape = p.shape ? `'${p.shape}'` : 'null';
  sql += `insert into public.puzzles (id, difficulty, kind, shape, puzzle) values ('${p.id}', ${p.difficulty}, '${p.kind}', ${shape}, ${q({ size: p.size, rows: p.rows, toPlay: p.toPlay })}) on conflict (id) do nothing;\n`;
  sql += `insert into public.puzzle_solutions (puzzle_id, points) values ('${p.id}', '{${p.points.join(',')}}') on conflict (puzzle_id) do nothing;\n`;
}
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log('seed.sql written:', LESSONS.length, 'lessons,', BANK.length, 'puzzles');
